export const getCityByName = (name: string): City | undefined => {
    return MOROCCAN_CITIES.find(c => c.name.toLowerCase() === name.toLowerCase());
};

export const searchCities = (query: string): City[] => {
    if (!query) return [];
    const lowerQuery = query.toLowerCase();
    return MOROCCAN_CITIES.filter(c => c.name.toLowerCase().startsWith(lowerQuery));
};
